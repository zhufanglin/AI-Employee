// T-33: local DB and a stub provider; never sends a request to RunningHub.
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { unlink } from 'node:fs/promises';
import { join } from 'node:path';
import { loadServerEnv } from './_env.mjs';
loadServerEnv();
process.env.MEDIA_DAILY_LIMIT = '2';
process.env.MEDIA_DAILY_SECONDS_LIMIT = '600';
process.env.MEDIA_CONCURRENT_LIMIT = '3';
const require = createRequire(new URL('../packages/server/package.json', import.meta.url));
const { PrismaClient } = require('@prisma/client');
const { MediaService } = require('./dist/media/media.service.js');
const { CreditsService } = require('./dist/billing/credits.service.js');
const { JwtService } = require('@nestjs/jwt');
const db = new PrismaClient();
const service = new MediaService(db, {});
service.provider = async () => ({ taskId: `t33-${randomUUID()}`, status: 'QUEUED' });
service.providerQuery = async () => ({ status: 'FAILED', errorMessage: 'mock failure' });
const check = (ok, message) => { if (!ok) throw new Error(message); console.log('PASS', message); };
let id;
try {
  const price = await db.mediaPricing.findUnique({ where: { taskType: 'image_gen' } });
  if (!price?.isActive || price.pricingMode === 'per_input_second' || price.pricePerRequest < 1) throw new Error('image_gen pricing missing');
  const amount = price.pricePerRequest;
  const user = await db.user.create({ data: { phone: null, passwordHash: 't33-smoke', credits: amount - 1 } });
  id = user.id;
  const request = () => service.submit(id, 'image_gen', { prompt: 'test', size: 7 });
  await request().then(() => { throw new Error('insufficient balance accepted'); }, e => check(e.status === 402, 'insufficient balance rejected'));
  check((await db.user.findUnique({ where: { id } })).credits === amount - 1, 'insufficient balance unchanged');
  await db.user.update({ where: { id }, data: { credits: amount * 3 } });
  const submissions = await Promise.allSettled([request(), request(), request()]);
  for (const result of submissions) if (result.status === 'rejected') console.log('REJECT', result.reason?.message);
  const accepted = submissions.filter(x => x.status === 'fulfilled').map(x => x.value);
  check(accepted.length === 2 && submissions.filter(x => x.status === 'rejected').length === 1, 'concurrent requests obey daily limit');
  check((await db.user.findUnique({ where: { id } })).credits === amount, 'only accepted tasks deducted');
  await Promise.all([service.getTask(id, accepted[0].taskId), service.getTask(id, accepted[0].taskId)]);
  check((await db.user.findUnique({ where: { id } })).credits === amount * 2, 'concurrent failure callbacks refund once');
  const refunds = await db.creditTransaction.count({ where: { userId: id, type: 'refund' } });
  check(refunds === 1, 'one refund transaction');
  const summary = await service.usageSummary(id, 7);
  check(summary.items.length === 1 && summary.items[0].count === 2 && summary.items[0].chargedCredits === amount && summary.items[0].unknownUpstreamCount === 2, 'summary reports credits and unknown upstream cost');
  await service.webhook(accepted[0].taskId, { status: 'SUCCESS' });
  check((await db.mediaTaskRecord.findUnique({ where: { taskId: accepted[0].taskId } })).status === 'FAILED', 'late success cannot overwrite refunded failure');
  process.env.MEDIA_DAILY_LIMIT = '4';
  process.env.MEDIA_CONCURRENT_LIMIT = '1';
  await request().then(() => { throw new Error('concurrent limit bypassed'); }, e => check(/同时进行/.test(e.message), 'concurrent task limit rejects before charge: ' + e.message));
  process.env.MEDIA_CONCURRENT_LIMIT = '3';
  await service.submit(id, 'video_gen', { image: 'openapi/ref.png', seconds: 601 }).then(() => { throw new Error('seconds limit bypassed'); }, e => check(/时长已达上限/.test(e.message), 'daily seconds limit rejects before charge'));
  await service.submit(id, 'lipsync', { image: 'openapi/ref.png', audio: 'openapi/ref.wav', seconds: 0 }).then(() => { throw new Error('unbounded audio accepted'); }, e => check(/大于零/.test(e.message), 'unbounded audio rejected'));
  await service.submit(id, 'image_gen', { nodeInfoList: [{ nodeId: '1' }] }).then(() => { throw new Error('custom node accepted'); }, e => check(/自定义/.test(e.message), 'custom nodes rejected'));
  await service.submit(id, 'indextts', { audio: 'openapi/ref.wav', text: 'test' }).then(() => { throw new Error('TTS accepted'); }, e => check(/暂不支持/.test(e.message), 'TTS temporarily disabled'));
  service.provider = async () => { throw new Error('connection lost'); };
  await request().then(() => { throw new Error('unknown upstream result accepted'); }, e => check(/待核对/.test(e.message), 'ambiguous submission requires review'));
  check((await db.user.findUnique({ where: { id } })).credits === amount, 'ambiguous submission does not immediately refund');
  const pending = (await service.pendingReviews()).find(x => x.userId === id);
  check(!!pending, 'ambiguous submission appears for review');
  const resolutions = await Promise.allSettled([service.resolveReview(pending.taskId, 'test-admin', { action: 'refund', reason: '上游确认未创建' }), service.resolveReview(pending.taskId, 'test-admin', { action: 'refund', reason: '上游确认未创建' })]);
  check(resolutions.filter(x => x.status === 'fulfilled').length === 1, 'concurrent manual refund resolves once');
  check((await db.user.findUnique({ where: { id } })).credits === amount * 2, 'manual refund restores balance once');
  check((await db.mediaTaskRecord.findUnique({ where: { taskId: pending.taskId } })).resultMeta.review.adminId === 'test-admin', 'manual refund retains audit');
  await request().catch(() => {});
  const pending2 = (await service.pendingReviews()).find(x => x.userId === id);
  const upstreamTaskId = `verified-${randomUUID()}`;
  await service.resolveReview(pending2.taskId, 'test-admin', { action: 'track', upstreamTaskId, reason: '上游确认已创建' });
  const tracked = await db.mediaTaskRecord.findUnique({ where: { taskId: upstreamTaskId } });
  check(tracked?.status === 'QUEUED' && tracked.resultMeta.review.adminId === 'test-admin', 'manual tracking links task and retains audit');
  await service.getTask(id, upstreamTaskId);
  check((await db.mediaTaskRecord.findUnique({ where: { taskId: upstreamTaskId } })).resultMeta.review.adminId === 'test-admin', 'tracking audit survives provider updates');
  const staleId = `reservation-${randomUUID()}`;
  const liveId = `reservation-${randomUUID()}`;
  await db.mediaTaskRecord.create({ data: { taskId: staleId, userId: id, taskType: 'image_gen', estimatedAmount: 0, status: 'SUBMITTING', createdAt: new Date(Date.now() - 11 * 60000) } });
  await db.mediaTaskRecord.create({ data: { taskId: liveId, userId: id, taskType: 'image_gen', estimatedAmount: 0, status: 'SUBMITTING' } });
  const reviews = await service.pendingReviews();
  check(reviews.some(x => x.taskId === staleId) && !reviews.some(x => x.taskId === liveId), 'only stale in-flight submissions appear for review');
  await service.resolveReview(liveId, 'test-admin', { action: 'refund', reason: '上游确认未创建' }).then(() => { throw new Error('active submission resolved'); }, e => check(e.status === 409, 'active submission cannot be manually resolved'));
  await service.resolveReview(staleId, 'test-admin', { action: 'refund', reason: '上游确认未创建' });
  check((await db.mediaTaskRecord.findUnique({ where: { taskId: staleId } })).status === 'FAILED', 'stale submission can be reconciled');
  process.env.MEDIA_DAILY_LIMIT = '20'; process.env.MEDIA_CONCURRENT_LIMIT = '10';
  service.provider = async () => ({ taskId: `t33-${randomUUID()}`, status: 'QUEUED' });
  const creditsService = new CreditsService(db);
  const startingBalance = (await db.user.findUnique({ where: { id } })).credits;
  await Promise.all([request(), creditsService.addCredits(id, amount, 'gift', 't33 parallel recharge'), creditsService.consumeCredits(id, amount, 't33 parallel model charge')]);
  check((await db.user.findUnique({ where: { id } })).credits === startingBalance - amount, 'media, recharge and model charge preserve balance under concurrency');
  const jwt = new JwtService({ secret: process.env.JWT_SECRET || 'dev-only-change-me' });
  const base = process.env.FCM_API || 'http://127.0.0.1:3000/api';
  const userToken = jwt.sign({ sub: id, role: 'user' });
  const adminToken = jwt.sign({ sub: id, role: 'admin' });
  const get = (path, token) => fetch(base + path, { headers: token ? { authorization: 'Bearer ' + token } : {} });
  check((await get('/media/usage/summary')).status === 401, 'user summary requires authentication');
  check((await get('/admin/media/pending-review', userToken)).status === 403, 'review list rejects regular users');
  check((await fetch(base + '/admin/media/pending-review/' + encodeURIComponent(liveId) + '/resolve', { method: 'POST', headers: { authorization: 'Bearer ' + userToken, 'content-type': 'application/json' }, body: JSON.stringify({ action: 'refund', reason: 'test rejection' }) })).status === 403, 'review resolution rejects regular users');
  check((await get('/admin/media/usage', userToken)).status === 403, 'admin summary rejects regular users');
  check((await get('/admin/media/usage', adminToken)).status === 200, 'admin summary available to administrator');
  check((await get('/media/usage/summary', userToken)).status === 200, 'user summary available to owner');
  const otherToken = jwt.sign({ sub: `other-${randomUUID()}`, role: 'user' });
  check((await (await get('/media/usage/summary', otherToken)).json()).items.length === 0, 'user summary isolates other accounts');
  const fakeFetch = globalThis.fetch;
  const archiveId = 't33-archive-' + randomUUID();
  try {
    process.env.PUBLIC_BASE_URL = ''; process.env.ARCHIVE_MEDIA_RESULTS = 'true';
    service.ossClient = () => null;
    globalThis.fetch = async () => new Response(Buffer.from('fake-image'), { status: 200, headers: { 'content-type': 'image/jpeg' } });
    const archived = await service.archiveResult(archiveId, 'https://example.invalid/image.jpg');
    check(archived.url === '/uploads/media/' + archiveId + '.jpg', 'local archive returns server-relative URL');
  } finally {
    globalThis.fetch = fakeFetch;
    await unlink(join(process.cwd(), 'uploads', 'media', archiveId + '.jpg')).catch(() => {});
  }
  console.log('T-33 isolated smoke PASS');
} finally {
  if (id) {
    await db.creditTransaction.deleteMany({ where: { userId: id } });
    await db.mediaTaskRecord.deleteMany({ where: { userId: id } });
    await db.user.delete({ where: { id } });
  }
  await db.$disconnect();
}
