import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { ChannelDispatcherService, DEGRADED_ACK_TEXT } = require('../packages/server/dist/channels/dispatcher.service');
const dispatcher = new ChannelDispatcherService({ employeeSlug: 'demo', ownerUserId: '' }, { channelInboundMsg: { create: async () => ({ id: 'claim' }) } }, {}, {}, {}, {});
let warning; dispatcher.logger = { warn: (s) => { warning = s; } };
const reply = await dispatcher.handleInbound({ channel: 'personal-wechat', fromUser: 'demo', msgId: 'fixture-id', msgType: 'text', content: '测试' });
assert.equal(reply, DEGRADED_ACK_TEXT); assert.match(reply, /还没绑定员工/);
assert.match(reply, /没有绑定入口，请联系管理员/);
assert.deepEqual(JSON.parse(warning), { reason: 'unbound', channel: 'personal-wechat', fromUser: 'demo', msgId: 'fixture-id' });
let pushed;
const wecom = new ChannelDispatcherService({ employeeSlug: 'demo', ownerUserId: '' }, {}, {}, { sendText: async (user, text) => { pushed = { user, text }; } }, {}, {});
wecom.logger = { warn: () => {}, log: () => {}, error: (message) => { throw new Error(message); } };
await wecom.handleInbound({ channel: 'wecom', fromUser: 'fixture', msgType: 'text', content: '测试' });
assert.deepEqual(pushed, { user: 'fixture', text: DEGRADED_ACK_TEXT });
const mp = new ChannelDispatcherService({ employeeSlug: 'demo', ownerUserId: '' }, { user: { findUnique: async () => null } }, {}, {}, { sendText: async (user, text) => { pushed = { user, text }; } }, {});
mp.logger = { warn: () => {}, log: () => {}, error: (message) => { throw new Error(message); } };
pushed = undefined;
await mp.handleInbound({ channel: 'wechat-mp', fromUser: 'fixture-mp', msgType: 'text', content: '测试' });
assert.deepEqual(pushed, { user: 'fixture-mp', text: DEGRADED_ACK_TEXT });
console.log('P47 unbound channel text and structured diagnostics PASS');
